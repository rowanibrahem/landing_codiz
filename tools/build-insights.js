function highlight(code, langName) {
  const key = ALIAS[(langName || "").toLowerCase()] || (langName || "").toLowerCase();
  const L = LANGS[key];
  if (!L) return esc(code);
  const rules = []; // [className, regex source] — sources contain no capture groups
  if (L.html) rules.push(["cm", "<!--[\\s\\S]*?-->"], ["kw", "<\\/?[A-Za-z][\\w-]*"]);
  if (L.tri) rules.push(["str", '"""[\\s\\S]*?"""'], ["str", "'''[\\s\\S]*?'''"]);
  if (L.c === "//" || L.css || key === "js" || L.block) rules.push(["cm", "\\/\\*[\\s\\S]*?\\*\\/"]);
  if (L.c) rules.push(["cm", L.c.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&") + "[^\\n]*"]);
  rules.push(["str", '"(?:\\\\.|[^"\\\\\\n])*"'], ["str", "'(?:\\\\.|[^'\\\\\\n])*'"]);
  if (L.tpl) rules.push(["str", "`(?:\\\\.|[^`\\\\])*`"]);
  rules.push(["num", "\\b\\d+(?:\\.\\d+)?\\b"], ["word", "[A-Za-z_$][\\w$]*"]);
  const re = new RegExp(rules.map((r) => "(" + r[1] + ")").join("|"), "g");
  const kw = new Set((L.kw || "").split(/\s+/).filter(Boolean)), lit = new Set((L.lit || "").split(/\s+/).filter(Boolean));
  let out = "", last = 0, m;
  while ((m = re.exec(code))) {
    if (m[0] === "") { re.lastIndex++; continue; }
    out += esc(code.slice(last, m.index));
    let g = 1; while (m[g] === undefined) g++;
    let cls = rules[g - 1][0];
    if (cls === "word") cls = kw.has(m[0]) || (L.ci && kw.has(m[0].toUpperCase())) ? "kw" : lit.has(m[0]) ? "lit" : "";
    out += cls ? `<span class="tk-${cls}">${esc(m[0])}</span>` : esc(m[0]);
    last = m.index + m[0].length;
  }
  return out + esc(code.slice(last));
}

function slugify(t) {
  return String(t).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "-").replace(/^-+|-+$/g, "") || "section";
}
function renderContent(blocks, root, lang) {
  const used = new Set(), toc = [];
  let imgN = 0;
  const html = blocks.map((b) => {
    switch (b.type) {
      case "heading": {
        const lvl = b.level === 3 ? 3 : 2;
        let id = slugify(plain(b.text)), n = 2; const base = id;
        while (used.has(id)) id = base + "-" + n++;
        used.add(id);
        toc.push({ id, level: lvl, text: plain(b.text) });
        return `<h${lvl} id="${esc(id)}" dir="auto">${inline(b.text)}</h${lvl}>`;
      }
      case "paragraph": return `<p dir="auto">${inline(b.text)}</p>`;
      case "list": {
        const tag = b.ordered ? "ol" : "ul";
        return `<${tag}>${(b.items || []).map((i) => `<li dir="auto">${inline(i)}</li>`).join("")}</${tag}>`;
      }
      case "quote":
        return `<blockquote dir="auto"><p>${inline(b.text)}</p>${b.cite ? `<cite>${inline(b.cite)}</cite>` : ""}</blockquote>`;
      case "image": {
        imgN++;
        if (b.missing || !b.src) return `<!-- missing image #${imgN}: ${esc(b.originalUrl || "")} -->`;
        const src = core.resolveAsset(b.src, root);
        const srcset = (b.srcset || []).map((v) => `${esc(core.resolveAsset(v.src, root))} ${v.width}w`).join(", ");
        const alt = b.alt || (lang === "en" ? `Illustration ${imgN}` : `صورة توضيحية ${imgN.toLocaleString("ar-EG")}`);
        const img = `<img src="${esc(src)}"${srcset ? ` srcset="${srcset}" sizes="(min-width: 840px) 760px, calc(100vw - 44px)"` : ""} alt="${esc(alt)}" loading="lazy" decoding="async"${b.width ? ` width="${esc(b.width)}"` : ""}${b.height ? ` height="${esc(b.height)}"` : ""}>`;
        return `<figure class="ins-fig"><a class="ins-zoom" href="${esc(src)}" target="_blank" rel="noopener" aria-label="${lang === "en" ? "Open image full size" : "فتح الصورة بالحجم الكامل"}">${img}</a>${b.caption ? `<figcaption dir="auto">${inline(b.caption)}</figcaption>` : ""}</figure>`;
      }
      case "callout":
        return `<aside class="ins-callout" dir="auto">${b.emoji ? `<span class="ins-callout-i" aria-hidden="true">${esc(b.emoji)}</span>` : ""}<div>${inline(b.text)}</div></aside>`;
      case "bookmark": {
        let host = ""; try { host = new URL(b.url).hostname.replace(/^www\./, ""); } catch (e) {}
        const meta = [b.publisher, b.author].filter(Boolean).join(" · ") || host;
        return `<a class="ins-bookmark" href="${esc(safeHref(b.url))}" target="_blank" rel="noopener noreferrer" dir="ltr"><span class="ins-bm-title">${esc(b.title || host)}</span>${b.description ? `<span class="ins-bm-desc">${esc(b.description)}</span>` : ""}<span class="ins-bm-meta">${esc(meta)}${host && meta !== host ? " · " + esc(host) : ""}</span></a>`;
      }
      case "code": {
        const label = b.filename || b.language || "code";
        return `<figure class="ins-code" dir="ltr"><div class="ins-code-bar"><span>${esc(label)}</span><button type="button" class="ins-copy" data-copy aria-label="Copy code">Copy</button></div><pre tabindex="0"><code class="language-${esc(b.language || "text")}">${highlight(String(b.code || "").replace(/\n$/, ""), b.language)}</code></pre></figure>`;
      }
      case "divider": return '<hr class="ins-hr">';
      default: return "";
    }
  }).join("\n");
  return { html, toc };
}

