function safeHref(u) {
  u = String(u).trim();
  return /^(https?:\/\/|mailto:|\/|#|\.{1,2}\/)/i.test(u) || /^[\w./-]+$/.test(u) ? u : "#";
}
// Inline mini-markup: **bold**, `code`, [text](url), newline → <br>; backslash escapes \* \` \[ \] \( \) \\
function inline(text) {
  const stash = [];
  const s0 = String(text == null ? "" : text).replace(/\\([\\*`\[\]()])/g, (m, c) => "\uE000" + (stash.push(c) - 1) + "\uE001");
  const restore = (x) => x.replace(/\uE000(\d+)\uE001/g, (m, i) => esc(stash[i]));
  return s0.split(/(`[^`]+`)/g).map((p) => {
    if (/^`[^`]+`$/.test(p)) return `<code dir="ltr">${restore(esc(p.slice(1, -1)))}</code>`;
    let s = esc(p);
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, u) => {
      const href = safeHref(u.replace(/&amp;/g, "&"));
      const ext = /^https?:/i.test(href);
      return `<a href="${esc(href)}"${ext ? ' target="_blank" rel="noopener noreferrer"' : ""}>${t}</a>`;
    });
    return restore(s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")).replace(/\n/g, "<br>");
  }).join("");
}
// Plain text of a marked-up string (for table of contents / ids)
function plain(text) {
  return String(text == null ? "" : text).replace(/\\([\\*`\[\]()])/g, "$1").replace(/\[([^\]]+)\]\([^)]*\)/g, "$1").replace(/\*\*([^*]+)\*\*/g, "$1").replace(/`([^`]+)`/g, "$1");
}

