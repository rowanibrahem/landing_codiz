function articlePage(a) {
  const root = "../../", lang = core.langOf(a, data), dir = core.dirOf(lang), cat = core.categoryOf(data, a.category);
  const site = (data.siteUrl || "").replace(/\/$/, "");
  const title = `${a.title} | ${data.siteName || "مدونة Codiz"}`;
  const related = sorted.filter((x) => x.slug !== a.slug)
    .sort((x, y) => (y.category === a.category) - (x.category === a.category)).slice(0, 3);
  const cover = a.coverImage || data.defaultOgImage || "";
  const ld = {
    "@context": "https://schema.org", "@type": "Article", headline: a.title, description: a.description,
    datePublished: a.publishedAt, inLanguage: lang, articleSection: cat.label,
    publisher: { "@type": "Organization", name: "Codiz" },
    ...(site ? { mainEntityOfPage: `${site}/insights/${a.slug}/` } : {}),
    ...(cover && site ? { image: /^https?:/.test(cover) ? cover : `${site}/${cover.replace(/^\//, "")}` } : {})
  };
  const back = lang === "en" ? "Back to the Blog" : "العودة إلى المدونة";
  const relH = lang === "en" ? "Related Articles" : "مقالات ذات صلة";
  const rc = renderContent(a.content, root, lang);
  const au = a.author && a.author.name ? a.author : null;
  if (au) ld.author = { "@type": "Person", name: au.name, ...(au.url ? { url: au.url } : {}) };
  const tocH = lang === "en" ? "Table of Contents" : "محتويات المقال";
  const toc = rc.toc.length >= (data.tocMinHeadings || 3)
    ? `<nav class="ins-toc" aria-label="${tocH}"><details open><summary>${tocH}</summary><ol>${rc.toc.map((t) => `<li class="l${t.level}"><a href="#${esc(t.id)}" dir="auto">${esc(t.text)}</a></li>`).join("")}</ol></details></nav>`
    : "";
  const byline = au
    ? `<div class="ins-byline"><span>${lang === "en" ? "By" : "بقلم"}</span> ${au.url ? `<a href="${esc(au.url)}" target="_blank" rel="noopener noreferrer" itemprop="author"><bdi>${esc(au.name)}</bdi></a>` : `<bdi itemprop="author">${esc(au.name)}</bdi>`}${au.title ? `<span class="ins-dot" aria-hidden="true">•</span><span dir="auto">${esc(au.title)}</span>` : ""}</div>`
    : "";
  const tags = (a.tags || []).length ? `<ul class="ins-tags" aria-label="${lang === "en" ? "Tags" : "الوسوم"}">${a.tags.map((t) => `<li dir="auto">${esc(t)}</li>`).join("")}</ul>` : "";
  const main = `<main class="ins-main">
<article class="ins-article is-${dir}" lang="${lang}" dir="${dir}" itemscope itemtype="https://schema.org/Article">
<div class="w ins-narrow">
<a class="ins-back" href="../index.html"><span aria-hidden="true">${core.ARROW}</span>${esc(back)}</a>
<header class="ins-article-head">
<a class="ins-tag tone-${esc(cat.tone || "lav")}" href="../index.html?category=${encodeURIComponent(cat.id)}">${esc(cat.label)}</a>
<h1 itemprop="headline">${esc(a.title)}</h1>
${a.hideIntro ? `<meta itemprop="description" content="${esc(a.description)}">` : `<p class="ins-intro" itemprop="description">${esc(a.description)}</p>`}
${byline}
<div class="ins-meta ins-meta--lg"><time datetime="${esc(a.publishedAt)}" itemprop="datePublished">${esc(core.formatDate(a.publishedAt, lang))}</time>${a.readingTime ? `<span class="ins-dot" aria-hidden="true">•</span><span>${esc(core.readingTimeText(a.readingTime, lang))}</span>` : ""}</div>
${tags}
</header>
${a.coverImage ? `<figure class="ins-fig ins-fig--cover"><img src="${esc(core.resolveAsset(a.coverImage, root))}" alt="${esc(a.coverAlt || "")}" decoding="async" fetchpriority="high"></figure>` : ""}
${toc}
<div class="ins-prose" itemprop="articleBody">
${rc.html}
</div>
<a class="ins-back ins-back--end" href="../index.html"><span aria-hidden="true">${core.ARROW}</span>${esc(back)}</a>
</div>
</article>
${related.length ? `<section class="ins-related" aria-labelledby="rel-h"><div class="w"><h2 id="rel-h" class="ins-related-h">${relH}</h2><div class="ins-grid">${related.map((r) => core.cardHTML(r, data, { root, base: "../" })).join("\n")}</div></div></section>` : ""}
</main>`;
  return pageShell({
    root, current: "article", path: `/insights/${a.slug}/`, title, description: a.description, type: "article",
    lang, image: cover, published: a.publishedAt, main,
    head: (au ? `<meta name="author" content="${esc(au.name)}">\n` : "") + `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, "\\u003c")}</script>`,
    scripts: '<script src="../../insights.js"></script>'
  });
}

