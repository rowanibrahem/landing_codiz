#!/usr/bin/env node
/*
 * Codiz Insights — static site generator (no dependencies, Node 16+).
 *
 *   node tools/build-insights.js                       # build from /insights-data.js
 *   node tools/build-insights.js --data <file.js>      # build from another data file (testing)
 *
 * Generates:
 *   insights/index.html              listing page   (route: /insights/)
 *   insights/<slug>/index.html       one page per article (route: /insights/<slug>/)
 *   site-base.css                    base styles copied from index.html's inline <style>
 * The header / footer are taken from index.html so they always match the main site.
 * Previously generated article folders that no longer exist in the data are removed.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const argv = process.argv.slice(2);
const di = argv.indexOf("--data");
const DATA_PATH = di >= 0 ? path.resolve(argv[di + 1]) : path.join(ROOT, "insights-data.js");
const OUT = path.join(ROOT, "insights");
const MARK = "<!-- generated by tools/build-insights.js -->";

const core = require(path.join(ROOT, "insights-core.js"));
const data = require(DATA_PATH);
const { esc } = core;

/* ───────────── validation ───────────── */
const errors = [], warns = [];
const articles = Array.isArray(data.articles) ? data.articles : [];
const catIds = new Set((data.categories || []).map((c) => c.id));
const slugs = new Set();
const BLOCKS = new Set(["heading", "paragraph", "list", "quote", "image", "code", "divider", "callout", "bookmark"]);
// Long articles can keep their blocks in a separate JSON file (contentFile) so the listing page stays light.
articles.forEach((a) => {
  if (!a.content && a.contentFile) {
    try { a.content = JSON.parse(fs.readFileSync(path.join(ROOT, a.contentFile), "utf8")); }
    catch (e) { errors.push(`${a.slug}: cannot read contentFile "${a.contentFile}": ${e.message}`); }
  }
});
const assetOk = (p) => !p || /^(https?:)?\/\//.test(p) || fs.existsSync(path.join(ROOT, p));
articles.forEach((a, i) => {
  const w = `articles[${i}]${a.slug ? " (" + a.slug + ")" : ""}`;
  ["id", "slug", "title", "description", "category", "publishedAt"].forEach((k) => { if (!a[k]) errors.push(`${w}: missing "${k}"`); });
  if (a.slug && !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(a.slug)) errors.push(`${w}: slug must be lowercase a-z, 0-9 and dashes`);
  if (a.slug && slugs.has(a.slug)) errors.push(`${w}: duplicate slug`);
  slugs.add(a.slug);
  if (a.category && !catIds.has(a.category)) errors.push(`${w}: unknown category "${a.category}"`);
  if (a.publishedAt && isNaN(new Date(a.publishedAt + "T00:00:00"))) errors.push(`${w}: invalid publishedAt`);
  if (a.lang && !["ar", "en"].includes(a.lang)) errors.push(`${w}: lang must be "ar" or "en"`);
  if (!Array.isArray(a.content) || !a.content.length) errors.push(`${w}: content must be a non-empty array`);
  (a.content || []).forEach((b, j) => {
    if (!b || !BLOCKS.has(b.type)) errors.push(`${w}: content[${j}] has unknown type "${b && b.type}"`);
    if (b && b.type === "image") {
      if (!assetOk(b.src)) errors.push(`${w}: content[${j}] image file not found: ${b.src}`);
      (b.srcset || []).forEach((v) => { if (!assetOk(v.src)) errors.push(`${w}: content[${j}] srcset file not found: ${v.src}`); });
    }
  });
  if (!assetOk(a.coverImage)) errors.push(`${w}: coverImage file not found: ${a.coverImage}`);
  if (a.tags && !Array.isArray(a.tags)) errors.push(`${w}: tags must be an array`);
});
if (errors.length) { console.error("Data errors:\n - " + errors.join("\n - ")); process.exit(1); }

/* ───────────── site chrome, parsed from index.html ───────────── */
const indexHtml = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
const baseCss = (indexHtml.match(/<style>\r?\n([\s\S]*?)<\/style>/) || [])[1];
const lkInner = (indexHtml.match(/<div class="lk"[^>]*>([\s\S]*?)<\/div>/) || [])[1];
const cta = (indexHtml.match(/<a class="btn l" href="#join">[\s\S]*?<\/a>/) || [])[0];
const toggle = (indexHtml.match(/<button type="button" class="nav-tg"[\s\S]*?<\/button>/) || [])[0] || "";
const footer = (indexHtml.match(/<footer>[\s\S]*?<\/footer>/) || [])[0] || "";
const tagline = (footer.match(/<div class="s">([\s\S]*?)<\/div>/) || [])[1] || "";
const copy = (footer.match(/<p>([\s\S]*?)<\/p>/) || [])[1] || "&copy; 2026 Codiz.";
if (!baseCss || !lkInner || !cta) { console.error("Could not parse header/styles from index.html"); process.exit(1); }
fs.writeFileSync(path.join(ROOT, "site-base.css"), baseCss.trimEnd() + "\n");

function rewriteHref(href, root) {
  if (/^(https?:|mailto:|tel:|\/\/)/i.test(href)) return href;
  if (href.startsWith("#")) return root + "index.html" + href;
  return root + href;
}
function header(root, current, inner) {
  const links = lkInner.replace(/href="([^"]*)"/g, (m, h) => {
    const nh = rewriteHref(h, root);
    return `href="${nh}"`;
  }).replace(/(<a [^>]*href="[^"]*insights\/index\.html"[^>]*)>/, '$1 aria-current="page">');
  return `<header class="hero ins-hero${current === "article" ? " ins-hero--sm" : ""}"><div class="w">
<nav><a href="${root}index.html"><img src="${root}logo.png" alt="Codiz"></a><div class="lk" id="site-links">${links}</div>${cta.replace('href="#join"', `href="${root}index.html#join"`)}${toggle}</nav>
${inner || ""}</div></header>`;
}
function footerHTML(root) {
  return `<footer><div class="w"><img src="${root}logo.png" alt="Codiz"><div class="s">${tagline}</div><p>${copy}</p></div></footer>`;
}

function pageShell(o) {
  const root = o.root, site = (data.siteUrl || "").replace(/\/$/, "");
  const url = site && o.path ? site + o.path : "";
  const img = o.image ? (/^(https?:)?\/\//.test(o.image) ? o.image : site ? site + "/" + o.image.replace(/^\//, "") : "") : "";
  const og = [
    ["og:type", o.type || "website"], ["og:title", o.title], ["og:description", o.description],
    ["og:site_name", data.siteName || "مدونة Codiz"], ["og:locale", o.lang === "en" ? "en_US" : "ar_AR"],
    url && ["og:url", url], img && ["og:image", img],
    ["twitter:card", img ? "summary_large_image" : "summary"], ["twitter:title", o.title], ["twitter:description", o.description],
    o.published && ["article:published_time", o.published]
  ].filter(Boolean).map(([k, v]) => `<meta property="${k}" content="${esc(v)}">`).join("\n");
  return `<!DOCTYPE html>
${MARK}
<html lang="ar" dir="rtl">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(o.title)}</title>
<meta name="description" content="${esc(o.description)}">
${url ? `<link rel="canonical" href="${esc(url)}">` : ""}
${og}
<link rel="icon" href="${root}logo.png">
<link href="https://fonts.googleapis.com/css2?family=Tajawal:wght@400;500;700;900&display=swap" rel="stylesheet">
<link rel="stylesheet" href="${root}site-base.css">
<link rel="stylesheet" href="${root}events.css">
<link rel="stylesheet" href="${root}instructors.css">
<link rel="stylesheet" href="${root}insights.css">
${o.head || ""}
<script>document.documentElement.classList.add('js')</script>
</head>
<body>
${header(root, o.current, o.hero)}
${o.main}
${footerHTML(root)}
${o.scripts || ""}
</body>
</html>
`;
}

